const {test}=require('node:test');
const assert=require('node:assert/strict');
const {openDemo}=require('./helpers/demo_harness.cjs');

test('delivered POTW offers both methods, flags a clear leader and preserves the human choice through switching and fresh scores',async t=>{
 const h=await openDemo({product:'select',role:'socials',journey:'socials'});t.after(h.close);
 const original=h.window.__fixtureDb.rpc.bind(h.window.__fixtureDb),writes=[];
 let revision=0,removed=false,scope='all';
 h.window.__fixtureDb.rpc=async(name,args)=>{
  if(name==='player_of_week_api'&&args.p_action!=='context')writes.push(args.p_action);
  const result=await original(name,args);
  if(name==='player_of_week_api'&&args.p_action==='context')return {data:{...result.data,award_scope:{...result.data.award_scope,key:scope},candidates:[120,60,50,40,30,20].map((runs,i)=>({key:'candidate-'+i+'-'+revision,snapshot_id:'card-'+revision,match_id:'match',team_id:'our-team',player_id:'player-'+i,name:'Player '+i,grade:'Test grade',runs:runs+revision,wickets:0,conceded:0,batting:[{runs:runs+revision}],bowling:[]})).filter((p,i)=>!removed||i!==0)}};
  return result;
 };
 await h.choose('#socialCreateMenu','player_week');
 const state=()=>h.window.eval('socialPlayerWeek.state(socialEnsure())');
 assert.ok(h.document.querySelector('[name=pwMethod][value=smart]').checked);
 assert.equal(state().winner,null);assert.equal(h.document.getElementById('pwSave').disabled,true);
 await h.click('[name=pwMethod][value=basic]');
 assert.equal(h.document.querySelectorAll('[name=pwMethod]:checked').length,1);
 assert.equal(h.document.querySelectorAll('#pwShortlist .pw-contender').length,5);
 assert.equal(h.document.querySelectorAll('#pwShortlist .pw-standout').length,1);
 assert.equal(h.document.getElementById('pwPreferNew'),null);
 assert.doesNotMatch(h.document.getElementById('pwShortlist').textContent,/vs team-mates|rest of match/);
 assert.equal(h.document.querySelector('[data-pw-open=method]').open,false);
 await h.click('#pwShortlist [data-pw-choose]');
 const chosen=state().winner.player_id;
 assert.equal(h.document.getElementById('pwSave').disabled,false);
 await h.click('[name=pwMethod][value=smart]');assert.equal(state().winner.player_id,chosen);
 assert.ok(h.document.getElementById('pwPreferNew'));
 await h.click('[name=pwMethod][value=basic]');assert.equal(state().winner.player_id,chosen);
 assert.deepEqual(writes,[],'Switching/choosing must not save or publish an award');
 revision++;
 await h.window.eval('socialPlayerWeek.load(socialEnsure(),{preserve:true})');await h.settle();
 assert.equal(state().winner.player_id,chosen);assert.equal(state().winner.runs,121);assert.ok(state().winner.key.endsWith('-1'));
 state().pending={};h.window.eval('socialPlayerWeek.render(socialEnsure())');await h.settle();
 assert.ok([...h.document.querySelectorAll('[name=pwMethod]')].every(e=>e.disabled));
 h.document.querySelector('[name=pwMethod][value=smart]').checked=true;
 h.document.querySelector('[name=pwMethod][value=smart]').dispatchEvent(new h.window.Event('change'));
 assert.equal(state().potwMode,'basic');state().pending=null;
 removed=true;await h.window.eval('socialPlayerWeek.load(socialEnsure(),{preserve:true})');await h.settle();
 assert.equal(state().winner,null);assert.equal(state().photo,null);assert.equal(h.document.getElementById('pwSave').disabled,true);
 assert.match(h.document.getElementById('pwStatus').textContent,/no longer in these scorecards/);
 await h.click('#pwShortlist [data-pw-choose]');assert.ok(state().winner);
 scope='other-group';await h.window.eval('socialPlayerWeek.load(socialEnsure(),{preserve:true})');await h.settle();
 assert.equal(state().winner,null,'A different award scope starts with no automatic winner');
 await h.window.eval('socialEnsure().playerWeek=null;socialPlayerWeek.render(socialEnsure())');await h.settle();
 assert.equal(state().potwMode,'basic');assert.equal(state().winner,null);
 assert.equal(h.window.eval("socialPlayerWeek.state({scope:'different-account:club',data:{timezone:'Australia/Sydney'}}).potwMode"),'smart');
 assert.equal(h.errors.length,0,h.errors.map(e=>e.message).join('\n'));
});
