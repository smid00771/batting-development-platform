const {test}=require('node:test'),assert=require('node:assert/strict');
const {openDemo}=require('./helpers/demo_harness.cjs');
test('captain review and coach observation share notes and videos without replacing either author',async t=>{
 const h=await openDemo({product:'both',role:'captain',journey:'team_review'});t.after(h.close);
 await h.choose('#teamReviewGroup','group-first');
 const fid=h.window.eval("demoSelections.fixtures.find(f=>f.details.grade_group_id==='group-first'&&f.details.days[0].date<todayIso()).id");
 await h.choose('#teamReviewFixture',fid);
 await h.click('[data-team-player="player-taylor"][data-team-choice="mostly"]');
 await h.choose('[data-team-dismissal="player-taylor"]','plan_execution');await h.click('#saveTeamReview');
 const rid=h.window.eval('ensureTeamReviewState().sessionId');assert.ok(rid);
 const row=h.document.querySelector('[data-team-review-row="player-taylor"]');
 assert.equal(row.children.length,3);assert.ok(row.children[1].querySelector('[data-team-dismissal]'));
 assert.equal(row.children[2].querySelector('[data-team-dismissal]'),null);
 // Switch only the authenticated demo member; retain the same saved data.
 h.window.eval("session.user.id='user-coach';membership=fixtureRows.club_memberships.find(m=>m.user_id==='user-coach');myPlayer=null;resetTeamReviewState();teamReviewCache=null;");
 await h.window.eval(`loadSavedTeamReview(${JSON.stringify(rid)})`);await h.settle();
 await h.click('[data-team-observation="player-taylor"]');
 const summary=h.document.querySelector('#staffDevelopmentForm .innings-contributions');assert.ok(summary);assert.equal(summary.open,false);
 assert.match(summary.textContent,/Jordan Ellis/);assert.match(summary.textContent,/Mostly/);
 assert.equal(h.document.querySelectorAll('input[name="staffBattingToPlan"]:checked').length,0,'Coach starts with own unanswered assessment');
 summary.querySelector('summary').click();assert.equal(summary.open,true);
 await h.choose('#staffMatchNote','Coach: wait for the fuller ball');
 await h.choose('#staffObservationVideoUrl','https://youtu.be/abcdefghijk?t=12');
 await h.choose('#staffObservationVideoNote','Second ball — choice to discuss');
 await h.click('#saveStaffMatchFeedback');
 const review=h.document.querySelector('[data-team-review-row="player-taylor"]');assert.ok(review);
 assert.match(review.textContent,/Jordan Ellis/);assert.match(review.textContent,/Coach: wait for the fuller ball/);
 assert.match(review.querySelector('.observation-video-link').href,/t=12$/);
 assert.equal(review.querySelector('[data-team-choice="mostly"]').getAttribute('aria-pressed'),'false');
 await h.click('[data-team-observation="player-taylor"]');assert.equal(h.document.querySelector('#staffMatchNote').value,'Coach: wait for the fuller ball');
 assert.match(h.document.querySelector('#staffDevelopmentForm .innings-contributions').textContent,/Jordan Ellis/);
 assert.equal(h.window.eval("fixtureRows.feedback['player-taylor'].matches.find(m=>m.id===document.getElementById('staffDevelopmentForm').dataset.matchId).coach_feedback.length"),2);
 await h.click('#backToFixture');
 h.window.eval("session.user.id='user-jordan';membership=fixtureRows.club_memberships.find(m=>m.user_id==='user-jordan');myPlayer=fixtureRows.players.find(p=>p.id==='player-jordan');resetTeamReviewState();teamReviewCache=null;");
 await h.window.eval(`loadSavedTeamReview(${JSON.stringify(rid)})`);await h.settle();await h.click('[data-team-observation="player-taylor"]');
 assert.equal(h.document.querySelector('input[name="staffBattingToPlan"]:checked').value,'mostly');
 assert.match(h.document.querySelector('#staffDevelopmentForm .innings-contributions').textContent,/Coach: wait for the fuller ball/);
 assert.match(h.document.querySelector('#staffDevelopmentForm .innings-contributions .observation-video-link').href,/t=12$/);
 assert.deepEqual(h.errors.map(e=>e.message),[]);
});
