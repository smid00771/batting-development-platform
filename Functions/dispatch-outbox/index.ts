const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'POST, OPTIONS',
};

function json(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...corsHeaders, 'Content-Type': 'application/json; charset=utf-8' },
  });
}

function esc(s: unknown) {
  return String(s ?? '').replace(/[&<>"']/g, c => ({ '&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;' }[c] || c));
}


function clubBattingText(s: unknown) {
  return String(s ?? '')
    .replace(/Batting Development Platform\s*\(\s*BDP\s*\)/gi, 'Club Batting')
    .replace(/Batting Development Platform/gi, 'Club Batting')
    .replace(/\bBDP\b/gi, 'Club Batting')
    .replace(/\b(?:Batting )?Philosophy Workshop\b/g, 'Batting Philosophy Workshop');
}

function cleanBaseUrl(raw: string) {
  if (!raw) return '';
  try {
    const u = new URL(raw);
    if (!['http:', 'https:'].includes(u.protocol)) return '';
    u.search = '';
    u.hash = '';
    return u.toString();
  } catch { return ''; }
}

function joinPublicLink(base: string, path: string) {
  if (!path) return base;
  if (/^https?:\/\//i.test(path)) return path;
  if (!base) return path;
  try {
    const u = new URL(base);
    const basePath = u.pathname.endsWith('/') ? u.pathname : u.pathname.replace(/[^/]+$/, '');
    u.pathname = basePath;
    u.search = path.startsWith('?') ? path.slice(1) : '';
    if (!path.startsWith('?')) return new URL(path, u).toString();
    return u.toString();
  } catch { return base + path; }
}

function money(cents: unknown, currency = 'AUD') {
  const n = Number(cents || 0) / 100;
  try { return new Intl.NumberFormat('en-AU', { style:'currency', currency:String(currency || 'AUD') }).format(n); }
  catch { return `$${n.toFixed(2)}`; }
}

