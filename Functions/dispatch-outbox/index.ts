async function sendResend(apiKey: string, from: string, to: string, subject: string, html: string, text: string, replyTo = '', idempotencyKey = '', timeoutMs = 0) {
  const body: Record<string, unknown> = { from, to: [to], subject, html, text };
  if (replyTo) body.reply_to = replyTo;
  const headers: Record<string, string> = { 'Authorization': `Bearer ${apiKey}`, 'Content-Type': 'application/json' };
  if (idempotencyKey) headers['Idempotency-Key'] = idempotencyKey.slice(0, 256);
  const response = await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers,
    body: JSON.stringify(body),
    ...(timeoutMs ? { signal: AbortSignal.timeout(timeoutMs) } : {}),
  });
  const raw = await response.text();
  let parsed: any = null;
  try { parsed = JSON.parse(raw); } catch { parsed = { message: raw }; }
  if (!response.ok) {
    const err: any = new Error(parsed?.message || `Resend returned ${response.status}`);
    err.status = response.status;
    throw err;
  }
  return parsed;
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: corsHeaders });
  if (req.method !== 'POST') return json({ error: 'POST required' }, 405);

  try {
    const authHeader = req.headers.get('Authorization') || '';
    if (!authHeader.startsWith('Bearer ')) return json({ error: 'Authentication required' }, 401);

    const supabaseUrl = Deno.env.get('SUPABASE_URL')!;
    const anonKey = Deno.env.get('SUPABASE_ANON_KEY')!;
    const serviceKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!;
    const resendKey = Deno.env.get('RESEND_API_KEY') || '';
    if (!supabaseUrl || !anonKey || !serviceKey) {
      return json({ error: 'Supabase Edge Function environment is incomplete.' }, 503);
    }

    const bearerToken = authHeader.slice('Bearer '.length).trim();
    // Pin the database webhook's credential separately from the runtime DB key.
    // Configure the existing webhook bearer value in Edge Function Secrets.
    const webhookToken = (Deno.env.get('OUTBOX_WEBHOOK_TOKEN') || '').trim();
    const webhookTokenConfigured = webhookToken.length >= 32;
    const webhookInvocation = webhookTokenConfigured && bearerToken === webhookToken;
    const serviceInvocation = webhookInvocation || (!!serviceKey && bearerToken === serviceKey);
    const userClient = createClient(supabaseUrl, anonKey, { global: { headers: { Authorization: authHeader } } });
    let user: any = null;
    let platformRole = '';

    if (!serviceInvocation) {
      const { data: userData, error: userError } = await userClient.auth.getUser();
      user = userData?.user || null;
      if (userError || !user) return json({ error: 'Authentication required' }, 401);
      const { data: role } = await userClient.rpc('get_my_platform_role');
      platformRole = String(role || '');
      if (!['owner','commercial_admin','support_admin','technical_admin'].includes(platformRole)) {
        return json({ error: 'Platform Admin access required' }, 403);
      }
    }

    const body = await req.json().catch(() => ({}));
    // Each INSERT webhook owns its inserted row. Reading the message back from
    // the database avoids trusting recipient/content fields in the request.
    const action = String(body.action || 'dispatch');
    const hasWebhookEnvelope = body.type != null || body.table != null || body.schema != null || body.record != null;
    let messageId = '';
    if (hasWebhookEnvelope) {
      if (body.type !== 'INSERT' || body.schema !== 'public' || body.table !== 'outbound_messages' ||
          !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(String(body.record?.id || ''))) {
        return json({ error: 'Expected an INSERT webhook for public.outbound_messages with a valid record id.' }, 400);
      }
      messageId = String(body.record.id);
    }
    const templateKey = String(body.template_key || '');
    if (templateKey && !['player_plans_open','mirelion_assist'].includes(templateKey)) {
      return json({ error: 'Unsupported retry template.' }, 400);
    }
    const notificationRevision = String(body.notification_revision || '');
    if (notificationRevision && (templateKey !== 'player_plans_open' || notificationRevision !== 'v0.8.52')) {
      return json({ error: 'Unsupported notification revision.' }, 400);
    }
    const service = createClient(supabaseUrl, serviceKey);
    const { data: settings, error: settingsError } = await service.from('platform_settings').select('*').eq('singleton', true).single();
    if (settingsError || !settings) return json({ error: settingsError?.message || 'Platform settings unavailable' }, 500);

    const fromName = String(settings.email_from_name || 'Club Batting').trim();
    const fromAddress = String(settings.email_from_address || 'onboarding@resend.dev').trim();
    const replyTo = String(settings.email_reply_to || '').trim();
    const from = `${fromName} <${fromAddress}>`;

    if (action === 'status') {
      return json({
        provider: 'resend', configured: !!resendKey, mode: settings.email_mode,
        from_name: fromName, from_address: fromAddress, reply_to: replyTo,
        testing_sender: /@resend\.dev$/i.test(fromAddress),
        automatic_delivery_ready: true,
        webhook_auth_configured: webhookTokenConfigured,
        public_app_url: cleanBaseUrl(Deno.env.get('APP_PUBLIC_URL') || ''),
        auth_mode: webhookInvocation ? 'webhook_token' : serviceInvocation ? 'service_role' : 'platform_admin',
      });
    }

    if (action === 'test') {
      if (serviceInvocation) return json({ error: 'Test sends require a signed-in Platform Admin.' }, 403);
      if (!resendKey) return json({ error: 'RESEND_API_KEY is not configured in Supabase Edge Function Secrets.' }, 503);
      const to = String(body.to || user?.email || '').trim().toLowerCase();
      if (!to || !to.includes('@')) return json({ error: 'Enter a valid test recipient.' }, 400);
      const result = await sendResend(
        resendKey, from, to,
        'Club Batting — email test',
        '<div style="font-family:Arial,sans-serif"><h2>Email provider connected ✓</h2><p>This message was sent by Club Batting through Supabase Edge Functions and Resend.</p></div>',
        'Email provider connected. This message was sent by Club Batting through Supabase Edge Functions and Resend.',
        replyTo,
        `bdp-test-${crypto.randomUUID()}`,
      );
      return json({ ok: true, provider_message_id: result?.id || null, to });
    }

    if (settings.email_mode !== 'live') return json({ ok: true, skipped: true, reason: 'Email mode is prototype.' });
    if (!resendKey) return json({ error: 'RESEND_API_KEY is not configured in Supabase Edge Function Secrets.' }, 503);
    const liveFrom = String(settings.email_live_from || '');
    if (!liveFrom) return json({ error: 'Live email start time is not set. Save Platform Settings with Email mode = Live provider before dispatching.' }, 409);

    const { error: cleanupError } = await service.rpc('expire_pending_club_invitations');

    const requestedLimit = Number(body.limit || 12);
    const limit = messageId ? 1 : Math.max(1, Math.min(25, Number.isFinite(requestedLimit) ? Math.floor(requestedLimit) : 12));
    const configuredBase = cleanBaseUrl(Deno.env.get('APP_PUBLIC_URL') || '');
    const requestBase = cleanBaseUrl(String(body.public_base_url || ''));
    const publicBaseUrl = configuredBase || requestBase;

    const stale = new Date(Date.now() - 10 * 60 * 1000).toISOString();
    await service.from('outbound_messages').update({ processing_at: null }).is('sent_at', null).is('failed_at', null).lt('processing_at', stale);

    let pendingQuery = service
      .from('outbound_messages')
      .select('id,recipient_email,template_key,subject,payload,club_id,prospect_id,sales_prospect_id,created_at,processing_at,cancelled_at')
      .is('sent_at', null)
      .is('failed_at', null)
      .is('cancelled_at', null)
      .is('processing_at', null)
      .gte('created_at', liveFrom);
    if (messageId) pendingQuery = pendingQuery.eq('id', messageId);
    if (templateKey) pendingQuery = pendingQuery.eq('template_key', templateKey);
    if (notificationRevision) pendingQuery = pendingQuery.eq('payload->>notification_revision', notificationRevision);
    const { data: pending, error: pendingError } = await pendingQuery
      .order('created_at', { ascending: true })
      .limit(messageId ? 1 : limit * 2);
    if (pendingError) return json({ error: pendingError.message }, 500);

    let sent = 0, failed = 0, deferred = 0, claimed = 0, providerAttempts = 0;
    const batchStarted = Date.now();
    const errors: { id: string; error: string }[] = [];

    for (const m of pending || []) {
      if (claimed >= limit) break;
      // Leave room for one final bounded provider request within the cron's
      // 55-second HTTP timeout. Remaining rows stay eligible for the next run.
      if (['player_plans_open','mirelion_assist'].includes(templateKey) && !messageId && Date.now() - batchStarted >= 40_000) break;
      if (m.processing_at) continue;
      const now = new Date().toISOString();
      const { data: lock } = await service.from('outbound_messages')
        .update({ processing_at: now })
        .eq('id', m.id)
        .is('sent_at', null)
        .is('failed_at', null)
        .is('cancelled_at', null)
        .is('processing_at', null)
        .select('id,processing_at,cancelled_at')
        .maybeSingle();
      if (!lock || lock.cancelled_at || !lock.processing_at) continue;
      claimed++;

      if (m.template_key === 'mirelion_assist') {
        const {data: alert, error: alertError} = await service.rpc('mirelion_assist_email', {p_message_id:m.id});
        if (alertError) {
          await service.from('outbound_messages').update({processing_at:null,last_error:'Assist alert validation unavailable.'}).eq('id',m.id);
          deferred++; continue;
        }
        if (!alert?.deliver) {
          await service.from('outbound_messages').update({cancelled_at:now,processing_at:null,last_error:'Assist update already read or no longer available.'}).eq('id',m.id);
          continue;
        }
        m.recipient_email=alert.recipient_email;
        m.payload=alert;
      }
      const to = String(m.recipient_email || '').trim().toLowerCase();
      if (!to || !to.includes('@')) {
        await service.from('outbound_messages').update({ failed_at: now, processing_at: null, last_error: 'Invalid recipient email' }).eq('id', m.id);
        failed++; continue;
      }

      if (['prospect_intro','prospect_follow_up','club_trial_reminder'].includes(String(m.template_key))) {
        const { data: suppressed } = await service.from('email_suppressions').select('email').eq('email', to).maybeSingle();
        if (suppressed) {
          await service.from('outbound_messages').update({ failed_at: now, processing_at: null, last_error: 'Recipient is suppressed from prospecting' }).eq('id', m.id);
          failed++; continue;
        }
      }

      const isPlayerIntroduction = m.template_key === 'player_plans_open' && m.payload?.notification_revision === 'v0.8.52';
      if ((isPlayerIntroduction || m.template_key === 'mirelion_assist' || ['prospect_intro','prospect_follow_up','club_trial_invitation','club_trial_reminder'].includes(m.template_key)) && !publicBaseUrl) {
        const message = 'APP_PUBLIC_URL must be configured before emails can include working Club Batting links.';
        await service.from('outbound_messages').update({ processing_at: null, last_error: message }).eq('id', m.id);
        deferred++;
        errors.push({ id: m.id, error: message });
        if (['player_plans_open','mirelion_assist'].includes(templateKey) && !messageId) break;
        continue;
      }
      if (m.template_key === 'club_trial_reminder' && (!/^app\.html\?close_invitation=[a-zA-Z0-9-]+$/.test(String(m.payload?.close_path || '')) || !/^\?prospect=[a-zA-Z0-9-]+$/.test(String(m.payload?.link_path || '')))) {
        const message = 'This reminder needs its saved activation and close-invitation links.';
        await service.from('outbound_messages').update({ failed_at: now, processing_at: null, last_error: message }).eq('id', m.id);
        failed++; errors.push({ id: m.id, error: message }); continue;
      }
      const rendered = renderMessage(m, publicBaseUrl);
      try {
        // A scheduled player-notification retry should drain steadily rather
        // than immediately hit Resend's request-rate limit again.
        if (['player_plans_open','mirelion_assist'].includes(templateKey) && !messageId && providerAttempts > 0) {
          await new Promise(resolve => setTimeout(resolve, 650));
        }
        providerAttempts++;
        const messageFrom = m.template_key === 'mirelion_assist' ? `Mirelion Assist <${fromAddress}>` : m.template_key === 'prospect_intro' ? `Club Batting Team <${fromAddress}>` : from;
        const result = await sendResend(resendKey, messageFrom, to, rendered.subject || clubBattingText(m.subject || 'Club Batting'), rendered.html, rendered.text, m.template_key === 'mirelion_assist' ? 'support@mirelionhq.com' : replyTo, `bdp-${m.id}`, (isPlayerIntroduction || ['club_trial_reminder','mirelion_assist'].includes(m.template_key)) ? 10_000 : 0);
        await service.from('outbound_messages').update({
          provider_name: 'resend', provider_message_id: result?.id || null,
          ...(rendered.subject ? { subject: rendered.subject } : {}),
          sent_at: new Date().toISOString(), failed_at: null, processing_at: null, last_error: null,
        }).eq('id', m.id);
        sent++;
      } catch (err) {
        const status = Number((err as any)?.status || 0);
        const message = err instanceof Error ? err.message : String(err);
        if (status === 0 || status >= 500 || status === 429) {
          await service.from('outbound_messages').update({ processing_at: null, last_error: message }).eq('id', m.id);
          deferred++;
        } else {
          await service.from('outbound_messages').update({ failed_at: new Date().toISOString(), processing_at: null, last_error: message }).eq('id', m.id);
          failed++;
        }
        errors.push({ id: m.id, error: message.slice(0, 180) });
        if ((status === 0 || status >= 500 || status === 429) && ['player_plans_open','mirelion_assist'].includes(templateKey) && !messageId) break;
      }
    }

    return json({ ok: true, claimed, sent, failed, deferred, errors, ...(cleanupError ? { cleanup_warning: cleanupError.message } : {}) });
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return json({ error: message || 'Email dispatch failed.' }, 400);
  }
});
