#!/usr/bin/env python3
"""Build public aggregate benchmarks from the privately retained NDCA analysis.

Usage: python Tools/build_ndca_benchmarks.py /path/to/analysis.json
The analysis and original exports stay private. No player names are emitted.
"""
import hashlib
import json
import sys
from pathlib import Path


def whole(value):
    return isinstance(value, int) and not isinstance(value, bool) and value >= 0


def build(data, source_sha):
    seasons = [f"{year}-{str(year + 1)[-2:]}" for year in range(2021, 2026)]
    files = [file for file in data["files"] if file["included"]]
    coverage = [(file["season"], file["filename_grade"]) for file in files]
    if len(files) != 20 or set(coverage) != {(s, g) for s in seasons for g in range(1, 5)}:
        raise ValueError("Expected one included export for each grade and season")
    # Reuse the analysed source exclusions: mismatched/repeated exports,
    # masked names and ambiguous duplicate name/club records are not counted.
    rows = [r for r in data["records"] if r["included"] and r["identity_eligible"]]
    grades = {}
    for grade in range(1, 5):
        selected = [r for r in rows if r["grade"] == grade]
        batting = [r for r in selected if all(whole(r[k]) for k in ("runs", "innings", "not_outs"))
                   and r["innings"] > 0 and r["not_outs"] <= r["innings"]]
        bowling = [r for r in selected if all(whole(r[k]) for k in ("balls_bowled", "wickets", "runs_conceded"))
                   and r["balls_bowled"] > 0]
        # Pool exposure, never averages of averages. Keep ducks, not-outs,
        # wicketless spells and short records; there is no success threshold.
        grades[grade] = {
            "batting": {"records": len(batting), "runs": sum(r["runs"] for r in batting),
                        "innings": sum(r["innings"] for r in batting),
                        "dismissals": sum(r["innings"] - r["not_outs"] for r in batting)},
            "bowling": {"records": len(bowling), "balls": sum(r["balls_bowled"] for r in bowling),
                        "wickets": sum(r["wickets"] for r in bowling),
                        "conceded": sum(r["runs_conceded"] for r in bowling),
                        "wicketless_records": sum(r["wickets"] == 0 for r in bowling)},
        }
    return {"version": "2026-10-18.1", "seasons": "2021/22–2025/26", "season_count": 5,
            "scope": "All recorded roles and match formats", "analysis_sha256": source_sha,
            "source_sha256": [f["sha256"] for f in files], "grades": grades}


if __name__ == "__main__":
    source = Path(sys.argv[1]).read_bytes()
    result = build(json.loads(source), hashlib.sha256(source).hexdigest())
    output = Path(__file__).resolve().parents[1] / "ndca-grade-benchmarks.js"
    output.write_text("// Generated by Tools/build_ndca_benchmarks.py; aggregate data only.\n"
                      "const freeze=value=>{Object.values(value).forEach(v=>{if(v&&typeof v==='object')freeze(v);});return Object.freeze(value);};\n"
                      "export const NDCA_BENCHMARKS=freeze(" + json.dumps(result, ensure_ascii=False, indent=2) + ");\n")
    print(f"Wrote {output.name}: four grades, five seasons, aggregate totals only")
